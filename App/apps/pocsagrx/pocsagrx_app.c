/*
 * POCSAG RX - a generic POCSAG (512 / 1200 / 2400 baud, direct FSK) receiver.
 * Unlike the LBJ receiver it is not tied to one rate, one address range or one
 * payload layout: it auto-detects the rate and shows any RIC, numeric or
 * alphanumeric, plus a raw codeword page.
 *
 * As EPIRB 406 / LBJ RX do, the RX audio reaches PA4 (the voice DAC pin, held at
 * mid-scale by the MCU DAC) and is sampled on ADC channel 4. The ADC runs at
 * 38.4 kHz = LCM(512,1200,2400), so every rate has an integer number of samples
 * per bit (75 / 32 / 16); the receiver is switched to RAW (RX HPF/LPF,
 * de-emphasis and AFC off) because the de-emphasis would destroy the NRZ
 * baseband. The loader restores the registers on exit.
 *
 * Three demodulators (512/1200/2400) run in parallel on the same sample stream
 * (auto-detect): each has its own matched-filter boxcar length, DPLL step, DC
 * and peak-tracker time constants and low-pass coefficients. Whichever rate
 * yields a valid sync + BCH + address codeword reports a message; wrong-rate
 * branches stay quiet (the model in test/model_rx.py shows no cross-talk).
 *
 * Keys: UP/DOWN pick the newer/older record (one step per press); 1 speaker;
 * 2 clear; 3 MSG/RAW page; 4 backlight always-on / timeout; 5 NUM/ALP toggle;
 * EXIT quit. Texts are read-only assets (gen_assets.py) to keep the 4 KiB
 * overlay free for code.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "pocsagrx_assets.h"   /* generated by gen_assets.py */
