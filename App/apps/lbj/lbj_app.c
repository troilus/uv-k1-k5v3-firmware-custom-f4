/* ---- PA4 bias (AC-coupled audio needs a mid-scale reference; EPIRB 406) ---- */
static void biasOn(uint32_t moder,uint32_t rcc){
    GPIOA_MODER=moder|(3u<<8);
    RCC_APBENR1=rcc|RCC_DACEN;
    DAC_CR=DAC_CR_BIAS;
    DAC_DHR12R1=BIAS_CODE;
    DAC_SWTRIGR=1u;
}
static void biasOff(uint32_t dac,uint32_t dhr,uint32_t rcc,uint32_t moder){
    DAC_CR=dac; DAC_DHR12R1=dhr; RCC_APBENR1=rcc; GPIOA_MODER=moder;
}
static void adcSelPA4(void){
    ADC_SMPR3=(g.savedSmpr3&~(7u<<SMP4_POS))|(((g.savedSmpr3>>SMP8_POS)&7u)<<SMP4_POS);
    ADC_SQR3=(g.savedSqr3&~0x1Fu)|ADC_CH_PA4;
}
static void adcRestore(void){ ADC_SQR3=g.savedSqr3; ADC_SMPR3=g.savedSmpr3; }
static uint16_t adcRead(void){
    ADC_CR2|=ADC_CR2_START;
    for(uint16_t n=0; !(ADC_SR&ADC_SR_EOC) && n<2000u; n++){}
    return (uint16_t)(ADC_DR&0x0FFFu);
}

/* ---- absolute cycle clock: ticks_ms * 48000 + position in the period ----
 * As SSTV and upstream POCSAG RX do: a blocking service (a full LCD blit is
 * ~11 ms) cannot lose a whole SysTick period the way a counter of SYST_VAL
 * differences can. The double read keeps the pair consistent across a period
 * wrap. Wraps every ~89 s (2^32 / 48 MHz) and the (int32_t)(now - next) gap
 * stays far under 44 s, so the signed comparison below stays valid. */
static uint32_t clkCyc(void){
    uint32_t t,v;
    do { t=g.A->ticks_ms(); v=SYST_VAL; } while(t!=g.A->ticks_ms());
    return t*48000u + (SYST_LOAD-v);
}

/* ---- one ADC sample through the model (DemodInt.sample) ---- */
static void dem_sample(dem_t *m,int32_t x){
    m->dc += (x - m->dc) >> DC_SHIFT;
    int32_t y = x - m->dc;
    int32_t o = (M_B0*y + M_B1*m->x1 + M_B0*m->x2 - M_A1*m->y1 - M_A2*m->y2) >> 14;
    m->x2=m->x1; m->x1=y; m->y2=m->y1; m->y1=o;
    /* One-bit matched filter: running sum of the last BOX samples. The sum is
     * BOX times the mean, but the slicer tracks its own peak-to-peak, so no
     * division is needed. Its null at the bit rate also rejects the data
     * harmonics (the weak-signal win). */
    m->bsum += o - m->box[m->bi];
    m->box[m->bi] = (int16_t)o;
    m->bi = (uint8_t)((m->bi + 1u) & (BOX - 1u));
    y = m->bsum;
    m->hi -= (m->hi - y) >> PK_SHIFT;
    if(y > m->hi) m->hi = y;
    m->lo += (y - m->lo) >> PK_SHIFT;
    if(y < m->lo) m->lo = y;
    /* Hysteresis slice (as the reference _d8): only flip beyond the mid +/- h
     * band, so noise near the threshold neither flips the bit nor kicks the
     * DPLL. */
    const int32_t mid = (m->hi + m->lo) >> 1;
    const int32_t h = (m->hi - m->lo) >> 6;
    uint8_t level = m->last;
    if(y > mid + h) level = 1u; else if(y < mid - h) level = 0u;
    if(level != m->last){
        int32_t err = m->ph;
        if(err > 32768) err -= 65536;
        m->ph -= err >> PLL_SHIFT;
        if(m->ph < 0) m->ph += 65536; else if(m->ph >= 65536) m->ph -= 65536;
    }
    m->last = level;
    int32_t p0 = m->ph;
    m->ph += PLL_STEP;
    if(p0 < 32768 && m->ph >= 32768) lbj_rx_bit(&g.rx, level);
    if(m->ph >= 65536) m->ph -= 65536;
}

/* One sample that was NOT read (the keys and the screen were served): the DPLL
 * phase runs on and the missing bit is taken as a zero, so a codeword keeps
 * its alignment across the slot (upstream Demod.skip). The filters and the
 * slicer state are left untouched, there is no ADC value for them. */
static void dem_skip(dem_t *m){
    int32_t p0 = m->ph;
    m->ph += PLL_STEP;
    if(p0 < 32768 && m->ph >= 32768) lbj_rx_bit(&g.rx, 0u);
    if(m->ph >= 65536) m->ph -= 65536;
}

/* ---- callbacks from the decoder core ---- */
/* LBJ address family receive window (matches the upstream receiver):
 * 1233980..1234020. Anything else is other POCSAG traffic and is dropped
 * before it can reach the history (note: the #if 0 PDU page used to show
 * every address - restore this filter's removal together with that page). */
static bool in_lbj(uint32_t a){ return (uint32_t)(a - 1233980u) <= 40u; }
/* The addresses the SUM page knows how to lay out: 1233999..1234002. */
static bool is_lbj(uint32_t a){ return (uint32_t)(a - 1233999u) <= 3u; }

/* ---- new-generation LB alert: the detail block -------------------------
 * 1234001/1234002: standalone detail of 30..64 chars at [0:len), or merged
 * after a 15-char short prefix ([15:65] of a 65-char report).
 * 1233999/1234000: only the merged form (len >= 65).
 * Inside the block: [0:4] 2 ASCII prefix chars, [4:7] 3-digit model code,
 * [7:12] loco number, [12:14] end flag, [14:30] GB2312 route, [30:39] and
 * [39:47] DDDMM.MMMM / DDMM.MMMM coordinates. */
#define DET_NIB    50u         /* detail block length (nibbles)   */
#define DET_MERGED 65u         /* 15-char short block + 50 detail */
#define DET_MIN30  30u         /* shortest standalone detail      */

/* true when the record carries a decodable detail block. */
static bool hasdet(uint32_t a,uint8_t len){
    if(!is_lbj(a)) return false;                 /* only 1233999..1234002 */
    if(a>=1234001u) return len>=DET_MIN30;       /* 1234001/1234002: standalone or merged */
    return len>=DET_MERGED;                      /* 1233999/1234000: merged only */
}

void lbj_emit_msg(const lbj_rx_t *r, const char *bcd, uint16_t len){
    if(!in_lbj(r->addr)) return;      /* keep the LBJ family only */
#ifdef LBJ_HIDE9
    /* Optional build: never keep a report whose train number starts with 9.
     * Mirrors puttrain(): the sticky prefix char comes first and only when
     * there is none does the short block's first non-blank digit show. A
     * standalone detail (30..64 chars) borrows the last short block. */
    {
        const char *p=(len>=30u&&len<65u)?g.sess:bcd;
        char c=g.pref[0]?g.pref[0]:g.pref[1];
        if(!c) for(uint8_t i=0;i<6u;i++) if(p[i]!=' '){ c=p[i]; break; }
        if(c=='9') return;
    }
#endif
    g.A->backlight_on();              /* wake the screen on RX activity */
    g.ledPhase=4u;                    /* green LED: on/off/on/off, 100 ms a step */
    rec_t *rec=g.hist[HISTORY-1u];
    for(uint8_t k=HISTORY-1u;k;k--) g.hist[k]=g.hist[k-1u];
    g.hist[0]=rec;
    rec->addr=r->addr;
    rec->func=r->func;
    /* [C6] the BCH verdict of this report: RF_ERR = not fully correctable (the
     * row ends with '!'), rec->cor = a codeword was repaired (ends with '*'). */
    rec->flags=(uint8_t)(r->err?RF_ERR:0u);
    rec->cor=r->cor;
    rec->rssi=(int16_t)g.A->rssi_dbm();     /* [C2] the strength right now */
    /* rec->flags (RF_LBJ) is only read by the #if 0 PDU page. */
    /* rec->flags=(uint8_t)((r->err?RF_ERR:0u) | (is_lbj(r->addr)?RF_LBJ:0u)); */
    rec->len=(uint8_t)(len>BCDMAX?BCDMAX:len);
    for(uint8_t i=0;i<rec->len;i++) rec->bcd[i]=bcd[i];
    if((r->addr==1233999u||r->addr==1234000u) && len>=15u){   /* remember the short block */
        for(uint8_t i=0;i<15u;i++) g.sess[i]=bcd[i];
        g.sessValid=true;
    }
    if(g.count<HISTORY) g.count++;
    g.cur=0;
    g.redraw=1u;
}

