/*
 * LBJ RX (development build) - receives Chinese railway LBJ (POCSAG 1200 baud,
 * direct FSK, ~821.24 MHz) and shows the decoded LBJ-family messages (address
 * window 1233980..1234020; other POCSAG traffic is ignored). Reference:
 * Sdr-Is-Fun/RTL_SDR_LBJ_RECEIVER and APRS RX on this firmware.
 *
 * The BK4829 has no POCSAG/FM-data demodulator, so as EPIRB 406 / APRS RX do,
 * the RX audio reaches PA4 (voice DAC pin, held at mid-scale by the MCU DAC) and
 * is sampled on ADC channel 4 at 19.2 kHz (16 samples per 1200-baud bit), timed
 * from SysTick, continuously. The receiver is switched to RAW (RX HPF/LPF,
 * de-emphasis and AFC off): the de-emphasis would destroy the NRZ baseband.
 * Each sample goes through the model in test/model_rx.py: slow baseline tracker,
 * low-pass biquad, a one-bit matched-filter boxcar (weak-signal win), symmetric
 * peak tracker with hysteresis, DPLL (65536/bit), then POCSAG sync / batch /
 * BCH(31,21) single-bit correction and the LBJ BCD layout.
 *
 * Keys: UP/DOWN pick the newer/older record (one step per press, no auto-repeat);
 * 1 speaker; 2 clear; 4 backlight always-on / timeout; 5 Chinese/English; EXIT
 * quit. SUM-only for now. The bottom status bar (tiny font) shows the key-state
 * hints (5 language, 4 backlight, 1 speaker) then x/y (selected record / total,
 * 1 = newest) and the live RSSI (-xx dBm), refreshed every 0.5 s and drawn from
 * launch (0/0). The PDU page and the M/S/W/F/B counter row are kept under #if 0
 * (they overflowed the 4 KiB overlay); restore them together.
 *
 * For the new-generation LB alert the SUM page decodes the detail block:
 * 1234001/1234002 carry a standalone 30..64-char block, or a merged 65-char
 * report (15-char short prefix + 50-char block); 1233999/1234000 carry the
 * merged form. Inside the block, [0:4] is 2 ASCII prefix chars, [4:7] the
 * 3-digit model code, [7:12] the loco number, [12:14] the end flag, [14:30]
 * the GB2312 route, [30:39]/[39:47] the DDDMM.MMMM/DDMM.MMMM coordinates.
 * The coordinates are shown in decimal degrees; the train/speed/km come from
 * a merged report's own short prefix, or from the most recent 1233999/1234000
 * short report. A detail report and its 1233999/1234000 base alert stay as
 * separate history entries. The route and the model name use the radio's
 * built-in 8x8 Chinese font; key 5 switches to an ASCII fallback (English
 * abbreviations like DF4C/SS7E, route hidden) for radios without it.
 */

