/* ---- formatting (repeated subtraction: no division) ---- */
static char *put(char *o,const char *s){ while(*s)*o++=*s++; return o; }
static unsigned sub(uint32_t *v,uint32_t d){ unsigned q=0; while(*v>=d){ *v-=d; q++; } return q; }
static const uint32_t P10U[]={1000000u,100000u,10000u,1000u,100u,10u,1u};
static char *putu(char *o,uint32_t v){
    bool lead=false;
    for(uint8_t i=0;i<7u;i++){
        unsigned c=sub(&v,P10U[i]);
        if(c||lead||i==6u){ *o++=(char)('0'+c); lead=true; }
    }
    return o;
}
/* decimal value of up to n chars (non-digits ignored) */static uint32_t digv(const char *p,uint8_t n){
    uint32_t v=0;
    for(uint8_t i=0;i<n;i++){ char c=p[i]; if(c>='0'&&c<='9') v=v*10u+(uint32_t)(c-'0'); }
    return v;
}
/* True when the n chars are digits plus the blanks a transmitter leaves in the
 * unused leading positions of a fixed-width number (the speed's hundreds, the
 * km post's thousands). A blank means 0 there, so it must not hide the value;
 * a '?' is a lost word and must still read as a dash, never a fake 0, and so
 * must an all-blank field (no number sent at all). The firmware's bcdpad(). */
static bool bcdpad(const char *p,uint8_t n){
    bool any=false;
    for(uint8_t i=0;i<n;i++){ char c=p[i]; if(c==' ') continue; if(c<'0'||c>'9') return false; any=true; }
    return any;
}
/* 3 chars -> decimal, or a dash when the field was not decoded at all. */
static char *putspd(char *o,const char *p){
    if(!bcdpad(p,3u)){ *o++='-'; return o; }
    return putu(o,digv(p,3u));
}
/* 5 BCD chars -> DDDD.D (blank / non-digit -> 0) */
static char *putkm(char *o,const char *p){
    for(uint8_t i=0;i<4u;i++){ char c=p[i]; *o++=(c>='0'&&c<='9')?c:'0'; }
    *o++='.';
    char c=p[4]; *o++=(c>='0'&&c<='9')?c:'0';
    return o;
}
/* n dashes: the rows a report carries no data for (the firmware's putdash) */
static char *putdash(char *o,uint8_t n){ while(n--) *o++='-'; return o; }

#ifdef LBJ_COORDS   /* [C3] coordinates: a compile option, off by default */
/* One DMS coordinate field, read exactly as the upstream Android receiver
 * reads the detail block: dg degree nibbles then MM MMMM minutes - all plain
 * decimal nibbles with no decimal point (lon [30:39], lat [39:47]). Writes
 * "DDD-MM.M<E>" and returns the new end, or NULL when a nibble is not a
 * digit, the minutes are >= 60 or the longitude starts above 1, so a
 * corrupted block shows no coordinates at all instead of a plausible wrong
 * pair. Degrees and minutes are copied digit by digit, as upstream prints
 * them (leading zeros kept); the minutes keep a single decimal (0.1' = about
 * 185 m) because the address and the dB figure share the row now. */
static char *putdms(char *o,const char *p,uint8_t dg,char hemi){
    for(uint8_t i=0;i<dg+6u;i++) if(p[i]<'0'||p[i]>'9') return NULL;
    if(p[dg]>'5') return NULL;                  /* minutes must be < 60  */
    if(dg==3u && p[0]>'1') return NULL;         /* longitude <= 19x      */
    for(uint8_t i=0;i<dg;i++) *o++=p[i];        /* degrees, as upstream  */
    *o++='-'; *o++=p[dg]; *o++=p[dg+1u]; *o++='.';
    *o++=p[dg+2u];
    *o++=hemi;
    return o;
}
#endif  /* LBJ_COORDS */

#ifndef LBJ_ROUTE_CN  /* [C5 route] the pinyin-initial route row is EN-only */
/* [C5 route] GB2312 level-1 (0xB0A1..0xD7F9) is sorted by pinyin, so the first
 * letter of a route character is a range lookup in this 23-entry boundary
 * table (Pinyin has no initial for I/U/V, hence 23 letters and not 26). The
 * table itself lives in the assets blob, not in the overlay: asset_read() drops
 * it into a stack buffer, so the 46 B never touch the 4 KiB code budget. */
static char cn_initial(const uint16_t *bnd,uint8_t hi,uint8_t lo){
    if(hi<0xB0u||hi>0xD7u)
        return '?';                                   /* level-2 or symbol */
    const uint16_t idx=(uint16_t)((uint16_t)(hi-0xB0u)*94u+(lo-0xA1u));
    uint8_t k=0;
    for(uint8_t i=1u;i<23u;i++){
        if(idx<bnd[i]) break;
        k=i;
    }
    return "ABCDEFGHJKLMNOPQRSTWXYZ"[k];
}
#endif  /* !LBJ_ROUTE_CN */

