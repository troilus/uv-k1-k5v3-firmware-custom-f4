/* ---- MCU registers (PY32F071, core and SysTick at 48 MHz, 10 ms period) ---- */
static inline volatile uint32_t *hw(uint32_t a){
    volatile uint32_t *p=(volatile uint32_t *)a;
    __asm__("" : "+l"(p));
    return p;
}
#define SYST_LOAD   (*(volatile uint32_t *)0xE000E014u)
#define SYST_VAL    (*(volatile uint32_t *)0xE000E018u)
#define ADC_SR      (hw(0x40012400u)[0x00/4])
#define ADC_CR2     (hw(0x40012400u)[0x08/4])
#define ADC_SMPR3   (hw(0x40012400u)[0x14/4])
#define ADC_SQR3    (hw(0x40012400u)[0x38/4])
#define ADC_DR      (hw(0x40012400u)[0x50/4])
#define GPIOA_MODER (*(volatile uint32_t *)0x50000000u)
#define DAC_CR      (hw(0x40007400u)[0x00/4])
#define DAC_SWTRIGR (hw(0x40007400u)[0x04/4])
#define DAC_DHR12R1 (hw(0x40007400u)[0x08/4])
#define RCC_APBENR1 (*(volatile uint32_t *)0x4002103Cu)
#define RCC_DACEN   (1u << 29)
#define DAC_CR_BIAS ((1u << 0) | (1u << 1) | (1u << 2) | (7u << 3))
#define BIAS_CODE   2048u
#define ADC_SR_EOC     (1u << 1)
#define ADC_CR2_START  ((1u << 22) | (1u << 20))
#define SMP8_POS       24u
#define SMP4_POS       12u
#define ADC_CH_PA4     4u
#define FS             19200u
#define CYC_PER_SAMPLE (48000000u / FS)
#define HOUSE_EVERY    960u    /* samples between key/screen slots (50 ms) */
#define BUSY_MAX       100u    /* serve keys anyway after 5 s inside a message */

#define REG_2B  0x2Bu          /* RX HPF/LPF + de-emphasis + AFC (EPIRB 406 RAW) */
#define REG_73  0x73u

/* ---- demodulator (test/model_rx.py, class DemodInt; the C is a transcription) */
#define DC_SHIFT   7
#define PK_SHIFT   8
#define PLL_STEP   4096        /* 65536 per bit / 16 samples per bit */
#define PLL_SHIFT  3
#define INT_SHIFT  9
#define INT_MAX    82          /* ~ PLL_STEP * 0.02 */
#define BOX        16u         /* 1-bit matched filter (samples per bit) */
#define M_B0       725         /* low-pass biquad 1500 Hz @ 19.2 kHz, Q14 */
#define M_B1       1451
#define M_A1     (-21674)
#define M_A2       8192

typedef struct {
    int32_t dc;
    int32_t x1, x2, y1, y2;
    int32_t hi, lo;
    int32_t ph, iint;
    int32_t bsum;                  /* running sum of the last BOX samples */
    int16_t box[BOX];
    uint8_t last, bi;
} dem_t;

/* ---- decoded-message history ---- */
#define HISTORY   8u
#define BCDMAX    96u

typedef struct {
    uint32_t addr;
    uint8_t  func, flags, len;
    char     bcd[BCDMAX];
} rec_t;
#define RF_ERR  1u             /* BCH could not correct the report */
#define RF_LBJ  2u             /* address belongs to the LBJ set */

static struct {
    const app_api_t *A;
    rec_t **hist;              /* newest first; records live on app_main's stack */
    char   *text;              /* formatting buffer (app_main's stack) */
    lbj_rx_t rx;
    uint8_t  count, cur, prevKey, redraw, page, top;
    bool     running, spk, blAlways, en, sessValid;
    uint8_t  busyFor, ledPhase;   /* ledPhase: green-LED double-blink steps */
    char     sess[16];         /* last 1233999/1234000 short block (train/spd/km) */
    int32_t  rssi;
    uint32_t tPrev, tCyc, rssiMs;
    uint32_t savedSqr3, savedSmpr3;
} g;
#define str g.text

/* ---- tiny freestanding helpers ---- */
void *memset(void *d, int c, size_t n){ uint8_t *p=d; while(n) p[--n]=(uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n){ uint8_t *p=d; const uint8_t *q=s; while(n){--n;p[n]=q[n];} return d; }

/* ---- formatting (repeated subtraction: no division) ---- */
static char *put(char *o,const char *s){ while(*s)*o++=*s++; return o; }
static unsigned sub(uint32_t *v,uint32_t d){ unsigned q=0; while(*v>=d){ *v-=d; q++; } return q; }
static const uint32_t P10U[]={1000000u,100000u,10000u,1000u,100u,10u,1u};
static char *putu(char *o,uint32_t v){
    bool lead=false;
    for(uint8_t i=0;i<7u;i++){
        unsigned c=sub(&v,P10U[i]);
        if(c||lead||i==6u){ *o++=(char)('0'+c); lead=true; }
    }
    return o;
}
/* decimal value of up to n chars (non-digits ignored) */static uint32_t digv(const char *p,uint8_t n){
    uint32_t v=0;
    for(uint8_t i=0;i<n;i++){ char c=p[i]; if(c>='0'&&c<='9') v=v*10u+(uint32_t)(c-'0'); }
    return v;
}
/* 5 BCD chars -> DDDD.D (blank / non-digit -> 0) */
static char *putkm(char *o,const char *p){
    for(uint8_t i=0;i<4u;i++){ char c=p[i]; *o++=(c>='0'&&c<='9')?c:'0'; }
    *o++='.';
    char c=p[4]; *o++=(c>='0'&&c<='9')?c:'0';
    return o;
}

/* DMS BCD (DDDMM.MMMM / DDMM.MMMM) -> decimal degrees with 4 decimals:
 * v = degrees*10000 + (minutes x10000)/60, then split. No float and no
 * division: sub() is repeated subtraction, so libgcc's __udivsi3 stays out.
 * Needs dg+6 chars at p. Two calls per redraw, worst case ~2 ms. */
static char *putdec(char *o,const char *p,uint8_t dg){
    uint32_t m=digv(p+dg,6u);                       /* MM.MMMM as x10000 */
    uint32_t v=digv(p,dg)*10000u+(uint32_t)sub(&m,60u);
    o=putu(o,sub(&v,10000u));                       /* whole degrees */
    *o++='.';
    for(uint8_t i=3u;i<7u;i++) *o++=(char)('0'+sub(&v,P10U[i]));
    return o;
}

#define ROWY(i) ((uint8_t)((i)*8u))

/* ---- PA4 bias (AC-coupled audio needs a mid-scale reference; EPIRB 406) ---- */
static void biasOn(uint32_t moder,uint32_t rcc){
    GPIOA_MODER=moder|(3u<<8);
    RCC_APBENR1=rcc|RCC_DACEN;
    DAC_CR=DAC_CR_BIAS;
    DAC_DHR12R1=BIAS_CODE;
    DAC_SWTRIGR=1u;
}
static void biasOff(uint32_t dac,uint32_t dhr,uint32_t rcc,uint32_t moder){
    DAC_CR=dac; DAC_DHR12R1=dhr; RCC_APBENR1=rcc; GPIOA_MODER=moder;
}
static void adcSelPA4(void){
    ADC_SMPR3=(g.savedSmpr3&~(7u<<SMP4_POS))|(((g.savedSmpr3>>SMP8_POS)&7u)<<SMP4_POS);
    ADC_SQR3=(g.savedSqr3&~0x1Fu)|ADC_CH_PA4;
}
static void adcRestore(void){ ADC_SQR3=g.savedSqr3; ADC_SMPR3=g.savedSmpr3; }
static uint16_t adcRead(void){
    ADC_CR2|=ADC_CR2_START;
    for(uint16_t n=0; !(ADC_SR&ADC_SR_EOC) && n<2000u; n++){}
    return (uint16_t)(ADC_DR&0x0FFFu);
}

/* ---- SysTick cycle counter (call at least every 10 ms) ---- */
static void clkStart(void){ g.tPrev=SYST_VAL; g.tCyc=0; }
static uint32_t clkCyc(void){
    uint32_t v=SYST_VAL;
    g.tCyc += (v<=g.tPrev) ? g.tPrev-v : g.tPrev+(SYST_LOAD+1u-v);
    g.tPrev=v;
    return g.tCyc;
}

/* ---- one ADC sample through the model (DemodInt.sample) ---- */
static void dem_sample(dem_t *m,int32_t x){
    m->dc += (x - m->dc) >> DC_SHIFT;
    int32_t y = x - m->dc;
    int32_t o = (M_B0*y + M_B1*m->x1 + M_B0*m->x2 - M_A1*m->y1 - M_A2*m->y2) >> 14;
    m->x2=m->x1; m->x1=y; m->y2=m->y1; m->y1=o;
    /* One-bit matched filter: running sum of the last BOX samples. The sum is
     * BOX times the mean, but the slicer tracks its own peak-to-peak, so no
     * division is needed. Its null at the bit rate also rejects the data
     * harmonics (the weak-signal win). */
    m->bsum += o - m->box[m->bi];
    m->box[m->bi] = (int16_t)o;
    m->bi = (uint8_t)((m->bi + 1u) & (BOX - 1u));
    y = m->bsum;
    m->hi -= (m->hi - y) >> PK_SHIFT;
    if(y > m->hi) m->hi = y;
    m->lo += (y - m->lo) >> PK_SHIFT;
    if(y < m->lo) m->lo = y;
    /* Hysteresis slice (as the reference _d8): only flip beyond the mid +/- h
     * band, so noise near the threshold neither flips the bit nor kicks the
     * DPLL. */
    const int32_t mid = (m->hi + m->lo) >> 1;
    const int32_t h = (m->hi - m->lo) >> 6;
    uint8_t level = m->last;
    if(y > mid + h) level = 1u; else if(y < mid - h) level = 0u;
    if(level != m->last){
        int32_t err = m->ph;
        if(err > 32768) err -= 65536;
        m->iint += err >> INT_SHIFT;
        if(m->iint > INT_MAX) m->iint = INT_MAX; else if(m->iint < -INT_MAX) m->iint = -INT_MAX;
        m->ph -= (err >> PLL_SHIFT) + m->iint;
        if(m->ph < 0) m->ph += 65536; else if(m->ph >= 65536) m->ph -= 65536;
    }
    m->last = level;
    int32_t p0 = m->ph;
    m->ph += PLL_STEP;
    if(p0 < 32768 && m->ph >= 32768) lbj_rx_bit(&g.rx, level);
    if(m->ph >= 65536) m->ph -= 65536;
}

/* ---- callbacks from the decoder core ---- */
/* LBJ address family receive window (matches the upstream receiver):
 * 1233980..1234020. Anything else is other POCSAG traffic and is dropped
 * before it can reach the history (note: the #if 0 PDU page used to show
 * every address - restore this filter's removal together with that page). */
static bool in_lbj(uint32_t a){ return (uint32_t)(a - 1233980u) <= 40u; }
/* The addresses the SUM page knows how to lay out: 1233999..1234002. */
static bool is_lbj(uint32_t a){ return (uint32_t)(a - 1233999u) <= 3u; }

/* ---- new-generation LB alert: the detail block -------------------------
 * 1234001/1234002: standalone detail of 30..64 chars at [0:len), or merged
 * after a 15-char short prefix ([15:65] of a 65-char report).
 * 1233999/1234000: only the merged form (len >= 65).
 * Inside the block: [0:4] 2 ASCII prefix chars, [4:7] 3-digit model code,
 * [7:12] loco number, [12:14] end flag, [14:30] GB2312 route, [30:39] and
 * [39:47] DDDMM.MMMM / DDMM.MMMM coordinates. */
#define DET_NIB    50u         /* detail block length (nibbles)   */
#define DET_MERGED 65u         /* 15-char short block + 50 detail */
#define DET_MIN30  30u         /* shortest standalone detail      */

/* true when the record carries a decodable detail block. */
static bool hasdet(uint32_t a,uint8_t len){
    if(!is_lbj(a)) return false;                 /* only 1233999..1234002 */
    if(a>=1234001u) return len>=DET_MIN30;       /* 1234001/1234002: standalone or merged */
    return len>=DET_MERGED;                      /* 1233999/1234000: merged only */
}

void lbj_emit_msg(const lbj_rx_t *r, const char *bcd, uint16_t len){
    if(!in_lbj(r->addr)) return;      /* keep the LBJ family only */
    g.A->backlight_on();              /* wake the screen on RX activity */
    g.ledPhase=4u;                    /* green LED: on/off/on/off, 10 ms a step */
    rec_t *rec=g.hist[HISTORY-1u];
    for(uint8_t k=HISTORY-1u;k;k--) g.hist[k]=g.hist[k-1u];
    g.hist[0]=rec;
    rec->addr=r->addr;
    rec->func=r->func;
    /* rec->flags (RF_ERR/RF_LBJ) is only read by the #if 0 PDU page. */
    /* rec->flags=(uint8_t)((r->err?RF_ERR:0u) | (is_lbj(r->addr)?RF_LBJ:0u)); */
    rec->len=(uint8_t)(len>BCDMAX?BCDMAX:len);
    for(uint8_t i=0;i<rec->len;i++) rec->bcd[i]=bcd[i];
    if((r->addr==1233999u||r->addr==1234000u) && len>=15u){   /* remember the short block */
        for(uint8_t i=0;i<15u;i++) g.sess[i]=bcd[i];
        g.sessValid=true;
    }
    if(g.count<HISTORY) g.count++;
    g.cur=0;
    g.redraw=1u;
}

