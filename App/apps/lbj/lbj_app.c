/* ---- input ---- */
static void handleKeys(void){
    const app_api_t *A=g.A;
    uint8_t key=A->get_key();
    /* One step per press: acting on the raw held key every house slot would
     * auto-repeat at ~20/s and skip records. Only a new key does anything, and
     * after release (prevKey=INVALID) nothing moves until the next press. */
    if(key==APP_KEY_INVALID||key==g.prevKey){ g.prevKey=key; return; }
    g.prevKey=key;
    int d=A->nav_dir(key);
    if(d){
        /* SUM only: one step per press through the record history. */
        int t=(int)g.cur+d;
        if(t<0) t=0;
        if(t>=(int)g.count) t=(int)g.count-1;
        if(t<0) t=0;
        if((uint8_t)t!=g.cur){ g.cur=(uint8_t)t; g.redraw=1u; }
        return;
    }
    g.redraw=1u;
    switch(key){
        case APP_KEY_EXIT: g.running=false; break;
        case APP_KEY_1:    g.spk=!g.spk; A->audio_path(g.spk); break;
        case APP_KEY_2:    g.count=g.cur=g.top=0;
                           /* reset the debug counters too (see lbj_dec.h):
                            * g.rx.syncs=g.rx.words=g.rx.ok=g.rx.fix=g.rx.bad=0;
                            * g.rx.msgs=g.rx.up=g.rx.dn=0; */
                           g.sessValid=false; break;
        /* case APP_KEY_3: g.page^=1u; g.top=0; g.cur=0; break;  PDU page off */
        case APP_KEY_4:    g.blAlways=!g.blAlways;
                           A->backlight_on();   /* re-arm now; house() holds it on when ON */
                           break;
#ifdef LBJ_ROUTE_CN
        case APP_KEY_5:    g.en=!g.en; break;   /* Chinese / English display */
#endif
        default: break;
    }
}

/* ---- keys and screen, between frames ---- */
static void house(void){
    const app_api_t *A=g.A;
    handleKeys();
    if(!g.running) return;
    /* [C2] no live RSSI any more: the strength is captured once, when a report
     * is received, and drawn on the address row. This also drops the 0.5 s full
     * screen redraw that the live value used to trigger.
    // g.rssi=A->rssi_dbm();
    // uint32_t now=A->ticks_ms();
    // if((uint32_t)(now-g.rssiMs)>=500u){ g.rssiMs=now; g.redraw=1u; }
     */
    if(g.blAlways) A->backlight_on();   /* re-arm BLTime every slot so it never expires */
    /* The fade only advances inside BACKLIGHT_Update(), which this service
     * drives: without it a dark panel would never light up after key 4 or a
     * decode wake-up (TurnOn just sets the target brightness). */
    A->backlight_update();
    if(!g.redraw) return;
    g.redraw=0;
    adcRestore();
    A->battery_sample();
    adcSelPA4();
    draw();
}

__attribute__((noinline))
static void listen(void){
    dem_t dm;                       /* on the stack: .bss counts toward the 4 KiB */
    memset(&dm,0,sizeof dm);
    dm.dc=BIAS_CODE; dm.hi=200; dm.lo=-200;   /* bsum is DC-free */

    adcSelPA4();
    uint32_t next=clkCyc();
    uint16_t cnt=0;
    uint16_t ledCnt=0;
    g.redraw=1u;
    while(g.running){
        while((int32_t)(clkCyc()-next)<0){}
        next+=CYC_PER_SAMPLE;
        dem_sample(&dm,adcRead());
        /* Green-LED double-blink: one step every 1920 samples (100 ms), i.e.
         * on 100 / off 100 / on 100 / off 100 - the same 100 ms "on" width the
         * radio's own A/B (RX-end) blink uses. The BK4819 GPIO6 write costs
         * ~40 us (< one sample period), so the sampler is not disturbed. */
        if(++ledCnt>=1920u){ ledCnt=0; if(g.ledPhase){ g.A->led((g.ledPhase&1u)==0u); g.ledPhase--; } }
        if(++cnt<HOUSE_EVERY) continue;
        cnt=0;
        if(g.rx.inmsg && ++g.busyFor<BUSY_MAX) continue;   /* keep sampling a message */
        g.busyFor=0;
        house();
        /* The samples the slot took were not read: run the bit clocks over them
         * and read the missing bits as zeros, so a batch keeps its codeword
         * alignment (upstream Demod.skip). */
        while((int32_t)(clkCyc()-next)>=0){
            next+=CYC_PER_SAMPLE;
            dem_skip(&dm);
        }
    }
    adcRestore();
}

__attribute__((section(".text.entry"),used))
void app_main(const app_api_t *api){
    rec_t recs[HISTORY];
    rec_t *hist[HISTORY];
    char text[40];
    for(uint8_t k=0;k<HISTORY;k++) hist[k]=&recs[k];
    g.A=api;
    g.hist=hist;
    g.text=text;
    g.prevKey=APP_KEY_INVALID;
    g.savedSqr3=ADC_SQR3; g.savedSmpr3=ADC_SMPR3;
    const uint32_t savedModer=GPIOA_MODER, savedDac=DAC_CR;
    const uint32_t savedRcc=RCC_APBENR1, savedDhr=DAC_DHR12R1;
    biasOn(savedModer,savedRcc);
    api->backlight_on();

    /* [C1] the speaker/display settings are no longer saved or loaded: the
     * overlay used to keep {bit0 speaker, bit1 English} in its app config
     * bytes. Every launch now starts from the defaults below - speaker off,
     * English display - and nothing is written back on exit. */
    // uint8_t cfg=0;
    // api->cfg_load(&cfg,1);
    // g.spk=(cfg&1u)!=0u;
    // g.en =(cfg&2u)!=0u;       /* bit1 set = ASCII fallback (no Chinese font) */
    g.spk=false;
    g.en =true;                 /* [C1] default: English display */
    g.page=0;

    /* RAW RX: HPF/LPF, de-emphasis and AFC off (EPIRB 406); the loader restores
     * the registers through RADIO_SetupRegisters on exit. */
    api->bk_write(REG_2B,(uint16_t)((api->bk_read(REG_2B)|0x0700u)&~0x0007u));
    api->bk_write(REG_73,(uint16_t)(api->bk_read(REG_73)|0x0010u));
#ifdef LBJ_PIN_FREQ
    /* [C7] Pin the receiver to the LBJ channel. The loader left RX on the user's
     * VFO, and the hardware comes back from the untouched gRxVfo->pRX->Frequency
     * through RADIO_SetupRegisters on exit - the same contract the RAW writes
     * above rely on, so there is nothing to restore here.
     *
     * This is the register set the firmware's own "change frequency while
     * running" code uses (app/spectrum.c SetF, app/chFrScanner.c ScanFastTune,
     * apps/epirb406 tune): the frequency pair, the 25 kHz IF filter, and REG_30
     * to 0 and back. The RAW bits above only bypass the audio-domain filters,
     * REG_43 keeps whatever the VFO menu asked for - which is a voice setting
     * when the VFO was not prepared for LBJ, so force it like AISRX does.
     * REG_30 is the important one: 0 and back makes the synthesizer recalibrate
     * and relock on the new frequency (ENABLE_VCO_CALIB lives in that register).
     * Outside an app that happens on every power-save wake-up (functions.c
     * FUNCTION_Select -> BK4819_Conditional_RX_TurnOn_and_GPIO6_Enable ->
     * BK4819_RX_TurnOn), so the resident receiver gets it for free - while an
     * overlay owns the foreground loop there is no wake-up to ride on. */
    api->bk_write(REG_38,(uint16_t)(LBJ_FREQ_HZ10 & 0xFFFFu));
    api->bk_write(REG_39,(uint16_t)(LBJ_FREQ_HZ10 >> 16));
    api->bk_write(REG_43,REG43_WIDE);
    const uint16_t r30 = api->bk_read(REG_30);
    api->bk_write(REG_30,0);
    api->bk_write(REG_30,r30);
#endif
    api->audio_path(g.spk);
    api->set_af(APP_AF_FM);
    api->delay_ms(50);

    g.running=true;
    listen();

    biasOff(savedDac,savedDhr,savedRcc,savedModer);
    api->led(false);           /* do not leave the green LED stuck mid-blink */
    api->set_af(APP_AF_MUTE);
    api->audio_path(false);
    /* [C1] cfg_save removed together with cfg_load. */
    // cfg=(uint8_t)((g.spk?1u:0u)|(g.en?2u:0u));
    // api->cfg_save(&cfg,1);
}
