/*
 * LBJ RX (development build) - receives Chinese railway LBJ (POCSAG 1200 baud,
 * direct FSK, ~821.24 MHz) and shows the decoded LBJ-family messages (address
 * window 1233980..1234020; other POCSAG traffic is ignored). Reference:
 * Sdr-Is-Fun/RTL_SDR_LBJ_RECEIVER and APRS RX on this firmware.
 *
 * The BK4829 has no POCSAG/FM-data demodulator, so as EPIRB 406 / APRS RX do,
 * the RX audio reaches PA4 (voice DAC pin, held at mid-scale by the MCU DAC) and
 * is sampled on ADC channel 4 at 19.2 kHz (16 samples per 1200-baud bit), timed
 * from SysTick, continuously. The receiver is switched to RAW (RX HPF/LPF,
 * de-emphasis and AFC off): the de-emphasis would destroy the NRZ baseband.
 * Each sample goes through the model in test/model_rx.py: slow baseline tracker
 * (512 samples, slower than a run of 13 equal bits), low-pass biquad, a one-bit
 * matched-filter boxcar (weak-signal win), symmetric peak tracker with
 * hysteresis, proportional DPLL (65536/bit), then POCSAG sync (popcount <= 2) /
 * batch / BCH(31,21) with the parity bit checked / the LBJ BCD layout. A
 * codeword the BCH cannot correct is not dropped: its 20 bits are lost in place
 * and shown as '?', so the rest of the report survives (soft erasure, upstream).
 *
 * Keys: UP/DOWN pick the newer/older record (one step per press, no auto-repeat);
 * 1 speaker; 2 clear; 4 backlight always-on / timeout; 5 Chinese/English (the
 * -DLBJ_ROUTE_CN build only); EXIT quit. SUM-only for now. The bottom status
 * bar (tiny font) shows the key-state hints (4 backlight, 1 speaker) then x/y
 * (selected record / total, 1 = newest), drawn from launch (0/0). The strength
 * now sits on the address row as "-87dB" in the small (not bold) font, taken
 * report was received rather than polled. Nothing is written to the app config
 * any more, so every launch starts from the defaults (speaker off, English).
 * The PDU page and the M/S/W/F/B counter row are kept under #if 0 (they
 * overflowed the 4 KiB overlay); restore them together.
 *
 * For the new-generation LB alert the SUM page decodes the detail block:
 * 1234001/1234002 carry a standalone 30..64-char block, or a merged 65-char
 * report (15-char short prefix + 50-char block); 1233999/1234000 carry the
 * merged form. Inside the block, [0:4] is 2 ASCII prefix chars, [4:7] the
 * 3-digit model code, [7:12] the loco number, [12:14] the end flag, [14:30]
 * the GB2312 route, [30:39]/[39:47] the coordinates as DDD MM MMMM (degrees
 * + minutes, plain decimal nibbles, no decimal point). They are shown as DMS
 * with the same validity check the upstream Android receiver applies; a bad
 * pair hides the row. The train/speed/km come from
 * a merged report's own short prefix, or from the most recent 1233999/1234000
 * short report. A detail report and its 1233999/1234000 base alert stay as
 * separate history entries. The model row always shows the English
 * abbreviation (DF4C/SS7E...); the GB2312 name table is gone from the assets.
 * The route row is a compile option: by default it reads "LINE " + the pinyin
 * initial of each GB2312 route character (level-1 is sorted by pinyin, so a
 * 23-entry boundary table in the assets is all it takes), while -DLBJ_ROUTE_CN
 * keeps the original behaviour - the Chinese route itself and the key-5
 * language toggle - for radios with the built-in 8x8 Chinese font. The
 * coordinates row is another compile option (LBJ_COORDS), off by default.
 *
 * The train number is prefixed with the 2 ASCII train-class chars at [0:4]
 * (K/T/D/C...), each packed as 2 BCD nibbles like the route: they are sticky in
 * g.pref (as LBJ_Console's lbjClass), so a short report with no detail block
 * still carries the last prefix seen. The top status bar is left exactly as the
 * firmware's UI_DisplayStatus() draws it - the app draws no title (an app title
 * there was wiped by UI_DisplayStatus()'s own UI_StatusClear() before blit) and
 * no frequency, which also freed the overlay bytes this prefix needed.
 */

