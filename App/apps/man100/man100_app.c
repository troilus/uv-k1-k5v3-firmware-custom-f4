/*
 * Man100 — "是男人就下100层" (It takes a man to descend 100 floors).
 *
 * A one-button-of-nerve descent for the 128x64 monochrome LCD, inspired by the
 * classic Wenquxing game. The whole shaft rises toward a spiked ceiling while
 * the man falls under gravity: steer him left and right to drop from one floor
 * to the next. Hollow floors are safe; the spiked ones, the ceiling and the
 * bottom of the screen all end the run in a single life (no continues).
 *
 * The generator always leaves a way down: each safe floor plans the next one
 * at most MAX_SHIFT pixels away, and the spiked floors are kept out of the
 * fall corridor between the two. Survive 100 floors and you win.
 *
 * Controls: LEFT/RIGHT (or 4 and 0) to move, F pauses, MENU restarts after
 * the end, EXIT quits.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "man100_assets.h"   /* generated by gen_assets.py */

#define W            128
#define TICK_MS       40u
#define CEIL_Y        12      /* the man dies when his top rises above this  */
#define ROW           14      /* vertical distance between floor rows        */
#define N_PLAT         5u     /* 14-px rows: ~4 on screen at once, +1 buffer */
#define SAFE_W        34      /* width of a safe floor                       */
#define SPIKE_W       24      /* a spiked floor, teeth at each end           */
#define MAX_SHIFT     22      /* horizontal step between two safe floors     */
#define MARGIN         8      /* keeps spikes clear of the fall corridor     */
#define X_MIN          2
#define X_MAX        124
#define MAN_W          8
#define MAN_H          8
#define BOOM          12u     /* explosion length in ticks                   */
#define WIN_FLOOR    100u     /* descend this many floors to win             */
#define NONE        0xFFu

enum { ST_PLAY, ST_OVER, ST_WIN, ST_TITLE };
enum { P_FREE, P_SAFE, P_SPIKE };
/* Countdowns, all decremented once per tick. */
enum { CD_BOOM, CD_BANNER, CD_WAIT, CD_COUNT };

typedef struct { uint8_t y, x, w, kind; } plat_t;

/* All the state in one struct: Thumb-1 code then reaches every field from a
 * single base address (one literal per function instead of one per global),
 * byte fields first so their offsets fit ldrb's 0..31 immediate. */
struct globals {
    uint8_t prevKey, titleTick;
    bool running, saver;
    /* NEW_GAME's values, read whole by new_game(): same order and sizes */
    uint8_t mode;
    bool paused;
    uint8_t riseAcc;
    uint8_t lastX, nextX;               /* current and planned safe floor x */
    bool spikeAllowed;
    uint8_t rows;
    uint8_t cd[CD_COUNT];
    /* end of NEW_GAME */
    uint8_t vy, on, lastRowY;
    uint16_t floor;
    int32_t bx, by, boomX, boomY;       /* man and explosion, top-left       */
    const app_api_t *api;
    plat_t plats[N_PLAT];
};
static struct globals g;
#define A (g.api)

_Static_assert(offsetof(struct globals, cd) + CD_COUNT - offsetof(struct globals, mode)
               == NEW_GAME_LEN, "new-game fields do not match NEW_GAME");
_Static_assert(offsetof(struct globals, lastRowY) < 32u, "byte fields out of ldrb range");

void *memset(void *dst, int value, size_t size)
{
    uint8_t *p = dst;
    while (size--) *p++ = (uint8_t)value;
    return dst;
}

static uint32_t rnd(void)
{
    return A->rand32() >> 8;   /* resident PRNG, seeded by the loader */
}

static void pixel(int x, int y)
{
    if ((unsigned)x >= W || (unsigned)y >= 64u) return;
    uint8_t *p = y < 8 ? &A->status_line[x] : &A->fb[(y >> 3) - 1][x];
    *p |= (uint8_t)(1u << (y & 7));
}

static void column(int x, int y, uint8_t v)
{
    for (; v; v >>= 1, y++)
        if (v & 1u) pixel(x, y);
}

/* Draw a column-major sprite (up to 8 rows high, LSB = top, w <= 8) read
 * from the assets at offset art. */
static void blit(int x, int y, uint16_t art, uint8_t w)
{
    uint8_t cols[8];
    const uint8_t *col = cols;
    A->asset_read(art, cols, w);
    while (w--) column(x++, y, *col++);
}

/* A centred bold text from the assets on LCD line `line`. */
static void say(uint16_t off, uint8_t line)
{
    char buf[TEXT_MAX];
    A->asset_read(off, buf, TEXT_MAX);
    A->print_bold(buf, 0, 127, line);
}

/* `width` digits of value (at most 5, no division) in tiny type on the HUD. */
static void hud_number(uint32_t value, uint8_t width, uint8_t x)
{
    uint16_t place[5];
    char buf[6];
    A->asset_read(PLACE, place, sizeof(place));
    const uint8_t first = (uint8_t)(5u - width);
    for (uint8_t i = 0; i < width; i++) {
        uint8_t digit = 0;
        while (value >= place[first + i]) {
            value -= place[first + i];
            digit++;
        }
        buf[i] = (char)('0' + digit);
    }
    buf[width] = 0;
    A->print_tiny(buf, x, 1, true, true);
}

/* Spawn one floor row at y. A spiked floor only goes outside the corridor
 * between the current safe floor and the planned next one; otherwise the row
 * gets that planned safe floor. */
static void spawn_row(int y)
{
    plat_t *p = &g.plats[0];
    for (uint8_t i = 0; i < N_PLAT; i++) if (!g.plats[i].kind) { p = &g.plats[i]; break; }
    g.lastRowY = (uint8_t)y;
    p->y = (uint8_t)y;

    if (g.spikeAllowed && (uint8_t)rnd() < 60u + g.floor / 2u) {
        const int left = (g.lastX < g.nextX ? g.lastX : g.nextX) - MARGIN - SPIKE_W;
        const int right = (g.lastX > g.nextX ? g.lastX : g.nextX) + SAFE_W + MARGIN;
        const uint8_t r = (uint8_t)rnd();
        int x = -1;
        if (left >= X_MIN && ((r & 1u) || right > X_MAX - SPIKE_W))
            x = X_MIN + (((r >> 1) * (left - X_MIN + 1)) >> 7);
        else if (right <= X_MAX - SPIKE_W)
            x = right + (((r >> 1) * (X_MAX - SPIKE_W - right + 1)) >> 7);
        if (x >= 0) {
            p->x = (uint8_t)x; p->w = SPIKE_W; p->kind = P_SPIKE;
            g.spikeAllowed = false;
            return;
        }
    }

    /* Safe floors shrink late in the game; the corridor above is still
     * computed with the widest SAFE_W, so it only gets more conservative. */
    p->x = g.nextX; p->w = SAFE_W; p->kind = P_SAFE;
    g.spikeAllowed = true;
    g.lastX = g.nextX;
    int d = (int)(rnd() & 63u) - 31;
    if (d > MAX_SHIFT) d = MAX_SHIFT;
    if (d < -MAX_SHIFT) d = -MAX_SHIFT;
    int n = g.lastX + d;
    if (n < X_MIN) n = X_MIN;
    if (n > X_MAX - SAFE_W) n = X_MAX - SAFE_W;
    g.nextX = (uint8_t)n;
}

static void new_game(void);

static void die(void)
{
    g.mode = ST_OVER;
    g.cd[CD_WAIT] = 40u;
    g.cd[CD_BOOM] = BOOM; g.boomX = g.bx; g.boomY = g.by;
    A->play_tone(200u, 60u);
}

static void win(void)
{
    g.mode = ST_WIN;
    g.cd[CD_WAIT] = 40u;
    A->play_tone(900u, 90u);
}

static bool supports(const plat_t *p)
{
    return g.bx + 6 > p->x && g.bx + 2 < p->x + p->w;
}

static void rise_step(void)
{
    g.lastRowY--;
    for (uint8_t i = 0; i < N_PLAT; i++) {
        plat_t *p = &g.plats[i];
        if (p->kind && --p->y < CEIL_Y) {
            p->kind = P_FREE;
            if (g.on == i) g.on = NONE;
        }
    }
    if (g.on != NONE) g.by--;   /* the man rides the floor up with the shaft */
    if (g.lastRowY <= 64 - ROW) {
        spawn_row(g.lastRowY + ROW);
        if (++g.floor >= WIN_FLOOR) win();
    }
}

static void tick(void)
{
    for (uint8_t i = 0; i < CD_COUNT; i++)
        if (g.cd[i]) g.cd[i]--;
    if (g.mode != ST_PLAY) return;

    if (!g.cd[CD_WAIT]) {   /* the shaft speeds up the deeper you survive */
        uint8_t sp = 3u + (uint8_t)(g.floor / 8u);
        if (sp > 12u) sp = 12u;
        g.riseAcc += sp;                       /* eighths of a pixel per tick */
        if (g.riseAcc >= 8u) { g.riseAcc -= 8u; rise_step(); }
    }

    if (g.on != NONE) {
        const plat_t *p = &g.plats[g.on];
        g.vy = 0;
        if (!supports(p)) g.on = NONE;
    }
    if (g.on == NONE) {
        const int prev = g.by + MAN_H;
        if (g.vy < 4u) g.vy++;   /* gravity: 1, 2, 3, 4 px per tick */
        g.by += g.vy;
        for (uint8_t i = 0; i < N_PLAT; i++) {
            const plat_t *p = &g.plats[i];
            if (!p->kind || prev > p->y + 2u || g.by + MAN_H < p->y || !supports(p)) continue;
            g.by = p->y - MAN_H;
            if (p->kind == P_SPIKE) { die(); return; }
            g.on = i;
            break;
        }
    }
    if (g.by < CEIL_Y || g.by > 56) die();
}

static void draw(void)
{
    A->display_clear(); A->status_clear();

    /* Spiked ceiling: 7-px tooth period started at x = -5, so the teeth span
     * the width with a small margin on both sides. */
    for (int x = -5; x < W; x += 7) blit(x, 8, SPR_TOOTH, 7);

    for (uint8_t i = 0; i < N_PLAT; i++) {
        const plat_t *p = &g.plats[i];
        if (p->kind == P_SAFE) {
            for (uint8_t k = 0; k < p->w; k++)   /* hollow 3-row pill, rounded ends */
                column(p->x + k, p->y, (k == 0u || k == p->w - 1u) ? 0x02u
                                       : (k == 1u || k == p->w - 2u) ? 0x07u : 0x05u);
        } else if (p->kind == P_SPIKE) {
            uint8_t spike[SPR_SPIKE_LEN];   /* one tooth period, read once per row */
            A->asset_read(SPR_SPIKE, spike, sizeof(spike));
            for (uint8_t k = 0, j = 0; k < p->w; k++, j = j == 6u ? 0u : j + 1u)
                column(p->x + k, p->y - 3, spike[j]);
        }
    }
    if (g.mode == ST_PLAY) blit(g.bx, g.by, SPR_MAN, MAN_W);
    if (g.cd[CD_BOOM]) blit(g.boomX, g.boomY, SPR_BOOM, MAN_W);

    /* HUD on the status line: F <floor> */
    char buf[TEXT_MAX];
    A->asset_read(T_FLOOR, buf, TEXT_MAX);
    A->print_tiny(buf, 1, 1, true, true);
    hud_number(g.floor > 999u ? 999u : g.floor, 3, 9);

    if (g.mode == ST_OVER) say(T_GAME_OVER, 3);
    else if (g.mode == ST_WIN) say(T_WIN, 3);
    else if (g.paused) say(T_PAUSE, 3);
}

static void new_game(void)
{
    memset(g.plats, 0, sizeof(g.plats));
    /* mode, paused, riseAcc, lastX, nextX, spikeAllowed, rows and the
       countdowns (boom, banner, wait) */
    A->asset_read(NEW_GAME, &g.mode, NEW_GAME_LEN);
    g.floor = 0;
    /* The first floor is always safe (NEW_GAME starts with spikeAllowed = 0):
       the man starts on it with a couple of seconds of headroom under the
       ceiling; below it the generator takes over. */
    spawn_row(38);            /* plats[0]: safe, the man starts here */
    spawn_row(38 + ROW);      /* plats[1] */
    spawn_row(38 + 2 * ROW);  /* plats[2]: off-screen buffer so he never falls out at once */
    g.rows = 0;
    g.on = 0;
    g.bx = g.plats[0].x + 8; g.by = 38 - MAN_H; g.vy = 0;
}

/* Title: the 1 KiB picture is streamed from the assets into the LCD buffers,
 * with a blinking prompt on the blank bottom page. */
static void draw_title(void)
{
    g.titleTick++;
    A->asset_read(ART_TITLE, A->status_line, W);
    A->asset_read(ART_TITLE + W, A->fb[0], 7u * W);
    if (g.titleTick & 16u) say(T_PRESS, 6);
}

static void poll_key(void)
{
    uint8_t key = A->get_key();
    if (key == APP_KEY_SAVER) { g.saver = true; return; }   /* freeze behind the saver */
    if (key == APP_KEY_WAKE || key == APP_KEY_PTT) { g.saver = false; key = APP_KEY_INVALID; }
    const bool press = key != g.prevKey;
    g.prevKey = key;
    if (key == APP_KEY_INVALID) return;
    if (press && key == APP_KEY_EXIT) { g.running = false; return; }

    if (g.mode != ST_PLAY) {
        if (press && key == APP_KEY_MENU && !g.cd[CD_WAIT]) new_game();
        return;
    }
    if (press && key == APP_KEY_F) { g.paused = !g.paused; return; }
    if (g.paused) return;

    int dx = 2 * A->nav_dir(key);   /* LEFT/RIGHT arrows (K1) or UP/DOWN (K5) */
    if (key == APP_KEY_4) dx = -2;
    if (key == APP_KEY_0) dx = 2;
    g.bx += dx;
    if (g.bx < 1) g.bx = 1;
    if (g.bx > W - MAN_W - 1) g.bx = W - MAN_W - 1;
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api)
{
    A = api;
    g.prevKey = A->get_key();
    g.running = true;   /* the rest of g starts zeroed (.bss) */
    A->led(false); A->backlight_on();
    g.mode = ST_TITLE;   /* MENU starts a descent, like after the end */

    while (g.running) {
        poll_key();
        if (!g.running) break;
        if (!g.saver) {   /* the saver freezes the game */
            if (g.mode == ST_TITLE) draw_title();
            else { if (!g.paused && g.mode == ST_PLAY) tick(); draw(); }
            A->blit_status(); A->blit_full();
        }
        A->backlight_update();
        A->delay_ms(TICK_MS);
    }
    A->led(false);
}
